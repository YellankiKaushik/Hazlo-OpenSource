import fs from 'node:fs/promises';
import path from 'node:path';
import { dependency, root, chromeOptions } from './lib.mjs';
const { chromium } = dependency('playwright');
const output = path.join(root, 'assets/screenshots');
await fs.mkdir(output, { recursive: true });
await fs.mkdir(path.join(root, 'assets/recordings'), { recursive: true });
const browser = await chromium.launch(chromeOptions);
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1.5, colorScheme: 'dark', locale: 'en-US', timezoneId: 'UTC', recordVideo: { dir: path.join(root, 'assets/recordings'), size: { width: 1280, height: 900 } } });
let blockedSyncs = 0;
await context.route('**/api/notion-sync', async route => {
  blockedSyncs++;
  await new Promise(resolve => setTimeout(resolve, 3000));
  await route.fulfill({ status: 401, contentType: 'application/json', body: JSON.stringify({ error: 'unauthorized' }) });
});
const page = await context.newPage();
const base = process.env.HAZLO_CAPTURE_URL || 'https://hazlo-opensource.vercel.app/';
const response = await page.goto(base, { waitUntil: 'networkidle', timeout: 60000 });
await page.getByRole('heading', { name: 'Hazlo by Kaushik' }).waitFor();
await page.getByRole('button', { name: 'Dark theme', exact: true }).click();
await page.waitForTimeout(300);
const snap = async (name) => page.screenshot({ path: path.join(output, name + '.png') });
await snap('dark-initial');
await page.getByRole('button', { name: 'Type instead', exact: true }).click();
await snap('manual-empty');
const transcript = 'Finish the landing page and review the Vercel deployment';
const input = page.getByLabel('Type instead', { exact: true });
await input.fill(transcript.slice(0, 27));
await snap('manual-partial');
await input.pressSequentially(transcript.slice(27), { delay: 52 });
await snap('manual-full');
await page.getByRole('button', { name: 'Save entry', exact: true }).click();
await page.getByText('Tasks (0/2)', { exact: true }).waitFor();
await snap('entry-pending');
await page.getByText('Sync failed', { exact: true }).waitFor();
await snap('entry-failed');
await page.reload({ waitUntil: 'networkidle' });
await page.getByText(transcript, { exact: true }).waitFor();
await snap('entry-restored');
await page.getByRole('button', { name: 'Light theme', exact: true }).click();
await page.waitForTimeout(300);
await snap('light-entry');
await page.getByRole('button', { name: 'Delete entry', exact: true }).click();
await snap('light-initial');
await page.getByRole('button', { name: 'Dark theme', exact: true }).click();
await snap('dark-clean');
const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, colorScheme: 'light', isMobile: true, hasTouch: true });
const mp = await mobile.newPage();
await mp.goto(base, { waitUntil: 'networkidle' });
await mp.getByRole('heading', { name: 'Hazlo by Kaushik' }).waitFor();
await mp.screenshot({ path: path.join(output, 'mobile-light.png') });
await mobile.close();
await fs.writeFile(path.join(root, 'assets/capture-manifest.json'), JSON.stringify({ capturedFrom: base, httpStatus: response.status(), viewport: { width: 1280, height: 900 }, screenshotScale: 1.5, fictionalTranscript: transcript, realManualEntry: true, extractedTasks: ['Finish the landing page', 'review the Vercel deployment'], persistenceVerifiedAfterReload: true, syncRequestsIntercepted: blockedSyncs, actualNotionRequestsSent: 0, microphoneRecorded: false, editorialNote: 'Terminal full stop omitted to match the current deterministic extractor and produce two tasks. Application code is unchanged.', syncResult: 'Intentionally blocked in fresh browser; failure/retry state is authentic. Successful sync visuals are separately labelled illustrative.' }, null, 2));
await context.close();
await browser.close();
console.log('Captured real desktop/manual/entry/persistence/theme/mobile UI. No production POST sent.');
