import fs from 'node:fs/promises';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { root, dependency, chromeOptions } from '../scripts/lib.mjs';
const { chromium } = dependency('playwright');
const output = path.join(root, 'assets/v2');
await fs.mkdir(path.join(output, 'screenshots'), { recursive: true });
await fs.mkdir(path.join(output, 'raw'), { recursive: true });
const browser = await chromium.launch(chromeOptions);
const context = await browser.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1.5, colorScheme: 'light', locale: 'en-US', timezoneId: 'UTC', recordVideo: { dir: path.join(output, 'raw'), size: { width: 1280, height: 900 } } });
let releaseSync;
let blocked = 0;
await context.route('**/api/notion-sync', async route => {
  blocked++;
  await new Promise(resolve => { releaseSync = resolve; });
  await route.fulfill({ status: 401, contentType: 'application/json', body: '{"error":"unauthorized"}' });
});
const started = Date.now();
const page = await context.newPage();
const events = {};
const mark = name => { events[name] = (Date.now() - started) / 1000; };
const snap = async name => page.screenshot({ path: path.join(output, 'screenshots', name + '.png') });
const url = process.env.HAZLO_CAPTURE_URL || 'https://hazlo-opensource.vercel.app/';
try {
  const response = await page.goto(url, { waitUntil: 'networkidle', timeout: 60000 });
  await page.getByRole('heading', { name: 'Hazlo by Kaushik' }).waitFor();
  await page.getByRole('button', { name: 'Dark theme', exact: true }).click();
  await page.waitForTimeout(250);
  await snap('dark-empty');
  await page.getByRole('button', { name: 'Light theme', exact: true }).click();
  await page.waitForTimeout(250);
  await snap('light-empty');
  mark('manualOpen');
  await page.getByRole('button', { name: 'Type instead', exact: true }).click();
  await snap('manual-empty');
  const transcript = 'Finish the landing page and review the deployment';
  await page.getByLabel('Type instead', { exact: true }).pressSequentially(transcript, { delay: 29 });
  mark('manualFull');
  await snap('manual-full');
  await page.waitForTimeout(300);
  mark('saveClick');
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await page.getByText('Tasks (0/2)', { exact: true }).waitFor();
  mark('tasksVisible');
  await snap('light-pending');
  const article = page.locator('article').first();
  await article.screenshot({ path: path.join(output, 'screenshots', 'entry-unchecked.png') });
  await page.locator('.task-check-button').nth(0).locator('..').screenshot({ path: path.join(output, 'screenshots', 'task-one.png') });
  await page.locator('.task-check-button').nth(1).locator('..').screenshot({ path: path.join(output, 'screenshots', 'task-two.png') });
  await page.getByRole('button', { name: 'Mark task complete', exact: true }).first().click();
  await page.waitForTimeout(230);
  await article.screenshot({ path: path.join(output, 'screenshots', 'entry-checked.png') });
  await page.locator('.task-check-button').nth(0).locator('..').screenshot({ path: path.join(output, 'screenshots', 'task-one-done.png') });
  await page.getByRole('button', { name: 'Mark task incomplete', exact: true }).click();
  await page.getByRole('button', { name: 'Dark theme', exact: true }).click();
  await page.waitForTimeout(250);
  await snap('dark-pending');
  if (releaseSync) releaseSync();
  await page.getByText('Sync failed', { exact: true }).waitFor();
  await snap('dark-failed');
  await article.screenshot({ path: path.join(output, 'screenshots', 'entry-failed.png') });
  await page.reload({ waitUntil: 'networkidle' });
  await page.getByText(transcript, { exact: true }).waitFor();
  await snap('restored');
  const manifest = { source: url, status: response.status(), events, transcript, terminalFullStopOmittedForCurrentExtractor: true, extractedTasks: ['Finish the landing page', 'review the deployment'], realCheckboxInteraction: true, realManualEntry: true, persistenceVerified: true, syncRequestsIntercepted: blocked, productionPostsSent: 0, successfulNotionWriteClaimed: false, browserProfile: 'fresh isolated context', microphone: 'not recorded; waveform is separately labelled illustrative' };
  const video = page.video();
  await context.close();
  const raw = await video.path();
  const clipStart = Math.max(0, events.manualOpen - .15);
  const clipDuration = Math.max(2, events.tasksVisible - clipStart + .3);
  const conversion = spawnSync('ffmpeg', ['-hide_banner','-loglevel','error','-y','-ss',String(clipStart),'-i',raw,'-t',String(clipDuration),'-an','-c:v','libx264','-crf','17','-pix_fmt','yuv420p','-movflags','+faststart',path.join(output,'manual-entry.mp4')], { encoding: 'utf8' });
  if (conversion.status !== 0) throw new Error(conversion.stderr);
  manifest.clip = { start: clipStart, duration: clipDuration, manualFull: events.manualFull - clipStart, save: events.saveClick - clipStart, tasks: events.tasksVisible - clipStart };
  await fs.writeFile(path.join(output, 'capture-manifest.json'), JSON.stringify(manifest, null, 2));
  console.log(JSON.stringify(manifest, null, 2));
} finally {
  if (releaseSync) releaseSync();
  await browser.close();
}
